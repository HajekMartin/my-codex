#!/usr/bin/env bash
# Install instructions only. Skill installation is explicit; see skills/README.md.
set -euo pipefail
umask 077

die() { printf 'Error: %s\n' "$*" >&2; exit 1; }
mode=install
if [[ $# -eq 1 && "$1" = --update ]]; then mode=update
elif [[ $# -ne 0 ]]; then die 'Usage: bash scripts/install.sh'; fi
repo_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
codex_dir=${CODEX_HOME:-${HOME:?HOME is required when CODEX_HOME is unset}/.codex}
[[ "$codex_dir" = /* ]] || die 'CODEX_HOME must be an absolute path.'
mkdir -p -- "$codex_dir"
codex_dir=$(cd -- "$codex_dir" && pwd -P)
target=$codex_dir/AGENTS.md
state=$codex_dir/.my-codex
lock=$codex_dir/.my-codex.lock
mkdir -- "$lock" 2>/dev/null || die "Installation is locked: $lock. If no installer is running, inspect and remove the empty lock directory."
cleanup() {
    rm -f -- "$lock/generated.md" "$lock/installed.md"
    rmdir -- "$lock" 2>/dev/null || true
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

[[ ! -e "$codex_dir/AGENTS.override.md" && ! -L "$codex_dir/AGENTS.override.md" ]] ||
    die "Global AGENTS.override.md would shadow this installation: $codex_dir/AGENTS.override.md. Resolve it manually."
[[ ! -L "$target" && ! -L "$state" ]] || die 'Refusing symlinked AGENTS.md or installation state.'

{
    printf '<!-- Generated by my-codex; edit source modules, then run update. -->\n\n'
    for module in AGENTS.md config/communication/instructions.md config/autonomy/instructions.md config/output-style/instructions.md config/git/instructions.md; do
        [[ -f "$repo_dir/$module" ]] || die "Missing source module: $module"
        printf '<!-- Source: %s -->\n\n' "$module"
        # Canonical UTF-8 without BOM, LF endings, and a final newline per module.
        LC_ALL=C awk 'NR == 1 { sub(/^\357\273\277/, "") } { sub(/\r$/, ""); print }' "$repo_dir/$module"
        printf '\n\n'
    done
} > "$lock/generated.md"
[[ $(wc -c < "$lock/generated.md") -lt 32768 ]] || die 'Generated instructions must be smaller than 32 KiB.'

if [[ -e "$state" ]]; then
    [[ -d "$state" && -f "$state/installed.md" && ! -L "$state/installed.md" ]] ||
        die "Unrecognized installation state: $state. Inspect it manually."
    [[ -f "$target" ]] && cmp -s -- "$target" "$state/installed.md" ||
        die "Installed AGENTS.md is missing or changed: $target. Preserve your edits and resolve manually."
    if cmp -s -- "$target" "$lock/generated.md"; then
        printf 'Already installed and unchanged: %s\n' "$target"
        exit 0
    fi
    [[ "$mode" = update ]] || die 'Source instructions changed. Run bash scripts/update.sh. Existing instructions were preserved.'
    cp -- "$lock/generated.md" "$lock/installed.md"
    mv -f -- "$lock/generated.md" "$target"
    mv -f -- "$lock/installed.md" "$state/installed.md"
    printf 'Updated managed instructions: %s\nStart a new Codex session.\n' "$target"
    exit 0
fi
[[ "$mode" = install ]] || die 'No managed installation. Run install.sh first.'
[[ ! -e "$target" && ! -L "$target" ]] ||
    die "Existing configuration preserved: $target. Review and move it aside yourself before installing; no automatic merge or overwrite."

# Publish a snapshot and target without replacing an existing filesystem entry.
cp -- "$lock/generated.md" "$lock/installed.md"
mkdir -- "$state"
if ! ln -- "$lock/installed.md" "$state/installed.md"; then
    rmdir -- "$state" 2>/dev/null || true
    die 'Could not create installation snapshot; AGENTS.md was not installed.'
fi
if ! ln -- "$lock/generated.md" "$target"; then
    rm -f -- "$state/installed.md"
    rmdir -- "$state" 2>/dev/null || true
    die 'Could not publish AGENTS.md; any existing target was preserved.'
fi
printf 'Installed complete instructions: %s\nStart a new Codex session. Skills were not changed.\n' "$target"
